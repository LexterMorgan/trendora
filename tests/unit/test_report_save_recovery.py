class _ExpiringRecord:
    """Mimics an ORM instance whose attributes expire after commit/rollback.

    A real ``Session.commit()`` expires every loaded attribute; reading one
    then triggers a reload. If the session is closed or detached, that read
    raises. This fake makes the same failure observable without a database:
    any attribute read after ``expire()`` raises ``DetachedInstanceError``.
    """

    def __init__(self, fingerprint, origin="client_supplied", report_id=None) -> None:
        import uuid

        self._values = {
            "id": report_id or str(uuid.uuid4()),
            "payload_hash": fingerprint,
            "snapshot_origin": origin,
            "status": "completed",
            "report": {},
        }
        self._expired = False

    def expire(self) -> None:
        self._expired = True

    def __getattr__(self, name):
        if name.startswith("_"):
            raise AttributeError(name)
        if self._expired:
            raise RuntimeError(
                "DetachedInstanceError: attribute read after commit/rollback"
            )
        return self._values[name]


class _RecordingSession:
    def __init__(self, results=None) -> None:
        self._results = list(results or [])
        self.added = []
        self.commits = 0
        self.rollbacks = 0
        self.flushes = 0
        self.statements = []
        self.savepoints = 0

    def begin_nested(self):
        self.savepoints += 1
        return _Savepoint(self)

    def execute(self, statement, *args, **kwargs):
        self.statements.append(statement)
        if not self._results:
            raise AssertionError(f"unexpected statement: {statement}")
        return _FakeResult(self._results.pop(0))

    def add(self, record) -> None:
        self.added.append(record)

    def flush(self) -> None:
        self.flushes += 1
        for record in self.added:
            if getattr(record, "id", None) is None:
                record.id = "00000000-0000-4000-8000-0000000000aa"

    def commit(self) -> None:
        self.commits += 1
        for record in self.added:
            if hasattr(record, "expire"):
                record.expire()

    def rollback(self) -> None:
        self.rollbacks += 1
        for record in self.added:
            if hasattr(record, "expire"):
                record.expire()


class _Savepoint:
    def __init__(self, session) -> None:
        self._session = session

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb) -> bool:
        if exc_type is None:
            self._session.flush()
        return False


class _FakeResult:
    def __init__(self, scalar) -> None:
        self._scalar = scalar

    def scalar_one_or_none(self):
        return self._scalar


class _Membership:
    def __init__(self, active=True) -> None:
        self.user_id = "00000000-0000-4000-8000-000000000001"
