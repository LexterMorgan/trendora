class TestAcknowledgmentSurvivesExpiry:
    """The acknowledgment must not read ORM attributes after the transaction."""

    def test_created_acknowledgment_is_readable_after_commit(self, monkeypatch) -> None:
        import trendora.api.report_save as module
        from trendora.api.report_save import outcome_for

        snapshot = _valid_snapshot()
        created_row = _ExpiringRecord(_fingerprint(snapshot))
        monkeypatch.setattr(
            module, "save_report_snapshot", lambda *a, **k: (created_row, True)
        )
        session = _RecordingSession([_Membership()])
        # Put the created row into the session so commit() expires it, exactly
        # as a real Session expires the instance it flushed.
        session.added.append(created_row)
        acknowledgment = _save(session, snapshot)
        assert acknowledgment.created is True
        assert session.commits == 1
        outcome = outcome_for(
            acknowledgment, request_id=UUID("00000000-0000-4000-8000-000000000001")
        )
        assert outcome.report_id
        assert outcome.snapshot_origin == "client_supplied"

    def test_replay_acknowledgment_is_readable_after_rollback(self, monkeypatch) -> None:
        import trendora.api.report_save as module
        from trendora.api.report_save import outcome_for

        snapshot = _valid_snapshot()
        existing = _Row(_fingerprint(snapshot))
        monkeypatch.setattr(
            module, "save_report_snapshot", lambda *a, **k: (existing, False)
        )
        session = _RecordingSession([_Membership()])
        session.added.append(existing)
        acknowledgment = _save(session, snapshot)
        assert acknowledgment.created is False
        outcome = outcome_for(
            acknowledgment, request_id=UUID("00000000-0000-4000-8000-000000000001")
        )
        assert outcome.report_id == existing._values["id"]
        assert outcome.snapshot_origin == "client_supplied"


class TestSaveRouteRoundTrip:
    """The real endpoint must save then recover the same id, one row only."""

    @pytest.mark.parametrize("include_receipt", [False, True])
    def test_missing_signing_key_refuses_new_source_recovery(self, monkeypatch, include_receipt):
        import trendora.api.report_save as save_module
        from trendora.api.deps import get_session as session_dep
        from trendora.research.recovery import issue_recovery_receipt
        from trendora.retention import report_source_deadline

        snapshot = _valid_snapshot()
        request_id = uuid.uuid4()
        receipt = issue_recovery_receipt(
            actor_id=_member().user_id, request_id=request_id,
            fingerprint=_fingerprint(snapshot),
            source_expires_at=report_source_deadline(snapshot, now=datetime.now(timezone.utc)),
            signing_key="fictional-recovery-test-key-no-real-value",
        )
        assert receipt is not None
        monkeypatch.setattr(save_module, "get_settings", lambda: SimpleNamespace(
            report_recovery_signing_key=None,
        ))
        session = _RecordingSession([_Membership(), None])
        app = create_test_app()
        app.dependency_overrides[session_dep] = lambda: session
        response = TestClient(app).post("/api/v1/research/reports/save", json={
            "schema_version": 1, "request_id": str(request_id), "snapshot": snapshot,
            "recovery_receipt": receipt if include_receipt else None,
        })
        assert response.status_code == 422
        assert response.json()["error"]["code"] == "invalid_report_snapshot"
        assert session.added == [] and session.commits == 0

    def test_route_save_then_recovery_does_not_duplicate(self, monkeypatch):
        import trendora.api.report_save as save_module
        from trendora.api.deps import get_session as session_dep

        snapshot = _valid_snapshot()
        request_id = str(uuid.uuid4())
        stored = {}

        def _fake_save(session, *, actor_id, request_id, snapshot, fingerprint, **kw):
            existing = stored.get((actor_id, request_id))
            if existing is None:
                row = _ExpiringRecord(fingerprint, origin="client_supplied")
                stored[(actor_id, request_id)] = row
                session.added.append(row)
                return row, True
            # A replay reads a fresh, un-expired row from the database.
            return _ExpiringRecord(
                fingerprint, origin="client_supplied", report_id=existing._values["id"]
            ), False

        monkeypatch.setattr(save_module, "save_report_snapshot", _fake_save)
        app = create_test_app()
        session = _RecordingSession([_Membership(), _Membership()])
        app.dependency_overrides[session_dep] = lambda: session
        client = TestClient(app)

        body = {"schema_version": 1, "request_id": request_id, "snapshot": snapshot}
        first = client.post("/api/v1/research/reports/save", json=body)
        assert first.status_code == 201, first.text
        first_id = first.json()["persistence"]["report_id"]

        second = client.post("/api/v1/research/reports/save", json=body)
        assert second.status_code == 200, second.text
        assert second.json()["persistence"]["report_id"] == first_id
        assert len(stored) == 1


