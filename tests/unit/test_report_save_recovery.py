def _valid_snapshot() -> dict:
    report = _report_service([]).build_report(**_query())
    response = to_report_response(report)
    return {
        field: response.model_dump(mode="json")[field]
        for field in ("status", "research", "evidence", "interpretation", "strategy", "ideation")
    }


def _fingerprint(snapshot: dict) -> str:
    return snapshot_fingerprint(snapshot)


class TestCanonicalSnapshot:
    def test_integral_float_and_int_hash_identically(self) -> None:
        a = _valid_snapshot()
        b = json.loads(json.dumps(a))
        a["research"]["query"]["result_limit"] = 20
        b["research"]["query"]["result_limit"] = 20.0
        assert canonical_snapshot_bytes(a) == canonical_snapshot_bytes(b)

    def test_key_order_does_not_change_the_fingerprint(self) -> None:
        snapshot = _valid_snapshot()
        reordered = dict(reversed(list(snapshot.items())))
        assert _fingerprint(snapshot) == _fingerprint(reordered)

    def test_changed_content_changes_the_fingerprint(self) -> None:
        snapshot = _valid_snapshot()
        changed = json.loads(json.dumps(snapshot))
        changed["research"]["query"]["topic"] = "a different topic"
        assert _fingerprint(snapshot) != _fingerprint(changed)

    def test_persistence_metadata_is_excluded(self) -> None:
        snapshot = _valid_snapshot()
        with_metadata = dict(snapshot)
        with_metadata["persistence"] = {"status": "saved", "report_id": "x"}
        assert canonical_snapshot_bytes(snapshot) == canonical_snapshot_bytes(with_metadata)

    def test_evidence_numeric_facts_survive_js_roundtrip(self) -> None:
        """A real JavaScript JSON round trip must not create a false conflict."""
        assert NODE is not None, "node is required for the round-trip regression"
        snapshot = _valid_snapshot()
        # A ratio-like float and an integral float are the interesting cases.
        snapshot["evidence"]["patterns"][0]["ratio"] = 1.0
        if snapshot["evidence"]["patterns"][0]["matching_reference_ids"]:
            pass
        script = (
            "let data='';process.stdin.on('data',c=>data+=c);"
            "process.stdin.on('end',()=>{"
            "const parsed=JSON.parse(data);"
            "process.stdout.write(JSON.stringify(parsed));});"
        )
        completed = subprocess.run(
            [NODE, "-e", script],
            input=json.dumps(snapshot),
            capture_output=True,
            text=True,
            timeout=30,
            cwd=REPO_ROOT,
        )
        assert completed.returncode == 0, completed.stderr
        roundtripped = json.loads(completed.stdout)
        assert _fingerprint(snapshot) == _fingerprint(roundtripped)


